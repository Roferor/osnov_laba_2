/*3) Дан прямоугольный массив цифр (карта высот 10х10). 
Нужно найти локальные минимумы (точки, которые меньше всех своих четырех соседей вверх, вниз, влево, вправо и по диаганалям)
 (Массив: int matrix[10][10] = ... задавайте сразу в коде) */

 #include <iostream>
 using namespace std;

 int main(){
    bool f;
    int index_dot[100][2], size_index_dot = 0;
    int matrix[10][10] = {
    {42, 17, 93, 8, 65, 31, 74, 56, 22, 89},
    {11, 78, 45, 92, 3, 60, 27, 84, 51, 19},
    {67, 34, 90, 5, 48, 72, 16, 99, 41, 58},
    {23, 81, 54, 37, 76, 12, 69, 43, 88, 7},
    {95, 28, 61, 44, 85, 20, 53, 70, 14, 39},
    {6, 73, 49, 96, 25, 62, 87, 18, 55, 32},
    {80, 47, 13, 68, 91, 36, 59, 24, 77, 2},
    {35, 98, 21, 64, 9, 82, 46, 71, 30, 57},
    {52, 15, 79, 40, 63, 4, 97, 26, 83, 50},
    {29, 66, 1, 86, 33, 75, 10, 94, 38, 21}
    };

    for(int i = 0;i < 10;i++){
        for(int j = 0;j < 10;j++){
            f = false;

            for(int i_2 = -1;i_2 < 2;i_2++){
                for(int j_2 = -1;j_2 < 2;j_2++){
                    if(!(((i + i_2 < 0) or (i + i_2 > 9)) or ((j + j_2 < 0) or (j + j_2 > 9)))){
                        if(matrix[i][j] > matrix[i_2 + i][j_2 + j]){
                            f = true;
                            break;
                        }
                    }
                }
                if(f){
                    break;
                }
            }

            if(!f){
                index_dot[size_index_dot][0] = i;
                index_dot[size_index_dot][1] = j;
                size_index_dot++;
            }

        }
    }

    for(int i = 0;i < size_index_dot;i++){
        cout << index_dot[i][0] << " ";
        cout << index_dot[i][1] << endl;
    }
 }